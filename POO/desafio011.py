'''Desafio 011 - Qual dos objetos abaixo seria o único abstrato da lista?
[ ] a) Sensor
[ ] b) Robô
[X] c) Notificação
[ ] d) Livro

Explicação: Em modelagem de sistemas orientados a objetos, diferenciamos coisas físicas (tangíveis) de conceitos abstratos
(intangíveis). Sensor, Robô e Livro representam coisas que existem fisicamente no mundo real. Já uma Notificação é um conceito
abstrato (um evento, uma mensagem ou um aviso), tornando-se o único objeto puramente intangível da lista.'''